import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ignoredDirectories = new Set(['.git', 'dist', 'node_modules', 'projects', '.tmp-lighthouse-tool']);
const sourceFiles = [];

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && ignoredDirectories.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(absolute);
    else if (/\.(?:html|js)$/i.test(entry.name)) sourceFiles.push(absolute);
  }
}

await collect(root);
const iconNames = new Set(['calculate', 'compare_arrows', 'notifications', 'notifications_active']);
for (const file of sourceFiles) {
  const source = await readFile(file, 'utf8');
  for (const match of source.matchAll(/material-symbols-outlined[^>]*>\s*([a-z0-9_]+)\s*</gi)) iconNames.add(match[1]);
  for (const match of source.matchAll(/\bicon\s*:\s*['"]([a-z0-9_]+)['"]/gi)) iconNames.add(match[1]);
}

const sortedIconNames = [...iconNames].sort();
const query = new URLSearchParams({
  family: 'Material Symbols Outlined:FILL,wght@0..1,100..700',
  icon_names: sortedIconNames.join(','),
  display: 'block'
});
const stylesheetUrl = `https://fonts.googleapis.com/css2?${query}`;
const headers = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36'
};
const stylesheetResponse = await fetch(stylesheetUrl, { headers });
if (!stylesheetResponse.ok) throw new Error(`Google Fonts CSS failed: ${stylesheetResponse.status}`);
const fontsDirectory = path.join(root, 'assets', 'fonts');
await mkdir(fontsDirectory, { recursive: true });
for (const file of await readdir(fontsDirectory)) {
  if (file.startsWith('material-symbols-outlined.')) await rm(path.join(fontsDirectory, file), { force: true });
}

let localCssBody = await stylesheetResponse.text();
const remoteFontUrls = [...new Set([...localCssBody.matchAll(/url\((https:\/\/[^)]+)\)/g)].map(match => match[1]))];
if (!remoteFontUrls.length) throw new Error(`Google Fonts CSS did not contain a font URL: ${localCssBody.slice(0, 300)}`);
let totalFontBytes = 0;
for (const [index, fontUrl] of remoteFontUrls.entries()) {
  const fontResponse = await fetch(fontUrl, { headers });
  if (!fontResponse.ok) throw new Error(`Material Symbols font failed: ${fontResponse.status}`);
  const fontBody = Buffer.from(await fontResponse.arrayBuffer());
  totalFontBytes += fontBody.length;
  const extension = fontBody.subarray(0, 4).toString('ascii') === 'wOF2' ? 'woff2' : 'ttf';
  const localName = `material-symbols-outlined.${index}.${extension}`;
  await writeFile(path.join(fontsDirectory, localName), fontBody);
  localCssBody = localCssBody.split(fontUrl).join(`../fonts/${localName}`);
}
if (totalFontBytes > 300_000) throw new Error(`Subset fonts are unexpectedly large: ${totalFontBytes} bytes.`);

const localCss = `/* Generated by scripts/update-material-symbols.mjs; ${sortedIconNames.length} icon glyphs. */\n${localCssBody}`;
await writeFile(path.join(root, 'assets', 'css', 'material-symbols.css'), localCss, 'utf8');

const remoteLink = /<link\b(?=[^>]*href=["']https:\/\/fonts\.googleapis\.com\/css2\?family=Material\+Symbols\+Outlined)[^>]*\/?>\s*/gi;
for (const file of sourceFiles.filter(file => file.endsWith('.html'))) {
  const source = await readFile(file, 'utf8');
  let inserted = false;
  const updated = source.replace(remoteLink, () => {
    if (inserted) return '';
    inserted = true;
    return '<link rel="stylesheet" href="assets/css/material-symbols.css?v=1">\n';
  });
  if (updated !== source) await writeFile(file, updated, 'utf8');
}

console.log(`Material Symbols subset updated: ${sortedIconNames.length} icons, ${Math.round(totalFontBytes / 1024)} KiB across ${remoteFontUrls.length} font file(s).`);
